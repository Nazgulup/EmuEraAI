// Browser-level verification of the bundled mobile UI, with a native bridge test double.
import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const web = path.resolve(import.meta.dirname, '..');
const assets = path.join(web, 'dist-maui');
const screenshots = path.resolve(web, '../../../tests/screenshots');
await fs.mkdir(screenshots, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', async route => {
    const url = new URL(route.request().url());
    const relative = decodeURIComponent(url.pathname).replace(/^\/wwwroot\//, '');
    const file = path.resolve(assets, relative);
    if (url.hostname !== 'game.local' || !file.startsWith(assets + path.sep)) return route.abort();
    try {
      const contentType = file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : file.endsWith('.html') ? 'text/html' : 'application/octet-stream';
      await route.fulfill({ body: await fs.readFile(file), contentType });
    } catch { await route.fulfill({ status: 404, body: '' }); }
  });
  await page.addInitScript(() => {
    window.eraTestMessages = [];
    window.chrome = { webview: { postMessage: raw => window.eraTestMessages.push(JSON.parse(raw)) } };
  });
  await page.goto('https://game.local/wwwroot/index.html');
  await page.getByRole('button', { name: 'AI 口上', exact: true }).click();
  await page.evaluate(() => window.__onMessage({ type: 'aiState', text: '林：今天的旅途顺利吗？\n这是已经执行一次的原口上。', status: '网络或接口异常，使用原口上。', character: '林', busy: false, hasEvent: true }));
  await page.getByRole('button', { name: '重新生成', exact: true }).click();
  await page.getByRole('button', { name: '恢复原口上 / 取消', exact: true }).click();
  const messages = await page.evaluate(() => window.eraTestMessages.filter(x => x.type.startsWith('ai')));
  assert.deepEqual(messages.map(x => x.type), ['aiGet', 'aiGenerate', 'aiRestore']);
  await page.screenshot({ path: path.join(screenshots, 'android-dialogue.png') });
  await page.evaluate(() => window.__onMessage({ type: 'aiState', text: '', status: 'AI 口上生成中', character: '林', busy: true, hasEvent: true, mode: 'pending', enabled: true, eventId: 'neutral-test', lineIndices: [], displayRevision: 0 }));
  assert.match(await page.locator('.ai-dialogue').textContent(), /生成中/);
  assert.equal(await page.getByRole('button', { name: '重新生成', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: '生成日志', exact: true }).click();
  await page.evaluate(() => window.__onMessage({ type: 'aiLog', text: '{"stage":"request.start","hook":"PRITRAIN_MESSAGE"}\n{"stage":"http.response","status":200}' }));
  assert.match(await page.getByLabel('生成日志', { exact: true }).inputValue(), /PRITRAIN_MESSAGE/);
  await page.getByRole('button', { name: '导出日志', exact: true }).click();
  await page.getByRole('button', { name: '测试已保存 API', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => window.eraTestMessages.slice(-3).map(x => x.type)), ['aiLog', 'aiExportLog', 'aiProbe']);
  await page.getByRole('button', { name: '游戏风格', exact: true }).click();
  assert.equal(await page.evaluate(() => window.eraTestMessages.at(-1).type), 'aiStyle');
  await page.evaluate(() => window.__onMessage({ type: 'aiStyle', text: '中性测试游戏：短句与第三人称叙述交替；开场承接当前事件。' }));
  assert.match(await page.getByLabel('当前游戏风格', { exact: true }).inputValue(), /第三人称/);
  await page.screenshot({ path: path.join(screenshots, 'android-generation-log.png') });
  await page.getByRole('button', { name: 'API 与酒馆预设', exact: true }).click();
  await page.getByLabel('API 基础地址', { exact: true }).fill('https://example.invalid/v1');
  await page.getByLabel('思考模式', { exact: true }).selectOption('disabled');
  await page.getByRole('button', { name: '刷新模型列表', exact: true }).click();
  await page.evaluate(() => { const request = window.eraTestMessages.at(-1); window.__onMessage({ type: 'aiModels', requestId: request.requestId, models: ['model-a', 'test-model'], error: '' }); });
  await page.getByLabel('可用模型', { exact: true }).selectOption('test-model');
  assert.equal(await page.getByLabel('API Key', { exact: true }).getAttribute('type'), 'password');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(screenshots, 'android-settings.png') });
  await page.evaluate(() => window.__onMessage({ type: 'aiPresetImported', text: JSON.stringify({ preserved: '文'.repeat(750000), prompts: [{ identifier: 'base', name: '角色语气', content: '根据 {{char}} 的性格和当前事件，生成一段简短对话。' }, { identifier: 'extra', name: '可选描写', content: '简短描写环境。' }] }) }));
  await page.getByLabel('启用 可选描写', { exact: true }).uncheck();
  await page.getByRole('button', { name: '角色语气 system', exact: true }).click();
  await page.locator('.ai-entry').first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(screenshots, 'android-preset-entries.png') });
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  const last = await page.evaluate(() => window.eraTestMessages.at(-1));
  assert.equal(last.type, 'aiSave'); assert.equal(last.settings.Model, 'test-model');
  assert.equal(last.settings.ThinkingMode, 'disabled'); assert.equal(last.settings.UsePresetOutputTokens, false); assert.equal(last.settings.UseGameStyle, true);
  assert.equal(JSON.parse(last.settings.PresetJson).prompts[1].enabled, false);
  assert.equal(JSON.parse(last.settings.PresetJson).preserved.length, 750000);
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  const reply = (await fs.readFile(path.resolve(web, '../../../logs/real-opening-20261118/reply-1.txt'), 'utf8')).trim();
  await page.evaluate(() => {
    window.__onMessage({ type: 'layout', windowWidth: 370, fontSize: 18, lineHeight: 24, fontName: 'monospace', state: 'WaitInput' });
    window.__onMessage({ type: 'aiState', enabled: true, mode: 'pending', text: '', eventId: 'opening', lineIndices: [0], displayRevision: 1 });
    window.__onTurn({ protocolVersion: 13, generation: 1, revision: 1, awaiting: { input: { type: 'IntValue' } }, diff: { lineOps: [{ type: 'clear_screen' }, { type: 'append', newLines: [
      { entries: [{ segments: [{ text: 'ORIGINAL_FALLBACK' }] }], isLineEnd: true },
      { entries: [{ segments: [{ text: '[1] 继续' }], button: { value: 1, isInteger: true, generation: 1 } }], isLineEnd: true },
    ] }], bgColor: '#283954' } });
  });
  await page.locator('.terminal').getByText('【AI 口上生成中…】', { exact: true }).waitFor();
  assert.doesNotMatch(await page.locator('.terminal').textContent(), /ORIGINAL_FALLBACK/);
  await page.evaluate(text => window.__onMessage({ type: 'aiState', enabled: true, mode: 'ai', text, eventId: 'opening', lineIndices: [0], displayRevision: 1 }), reply);
  await page.locator('.terminal').getByText('女战士先到了。', { exact: false }).waitFor();
  assert.equal(await page.locator('.terminal .term-btn').count(), 1);
  const menuBefore = await page.locator('.terminal .term-btn').boundingBox();
  const lastRow = await page.locator('.terminal .term-line').nth(-2).boundingBox();
  assert.ok(menuBefore.y >= lastRow.y + lastRow.height - 1, 'menu follows complete reply without overlap');
  const launch = await page.locator('.ai-launch').boundingBox();
  const firstReply = await page.locator('.terminal .term-line').first().boundingBox();
  assert.ok(launch.y + launch.height <= firstReply.y, 'AI controls do not cover the opening');
  await page.screenshot({ path: path.join(screenshots, 'android-inline-ai.png') });
  const replacement = '开始之前，先确认今天的安排。\n[777] <b>plain reply</b>';
  await page.evaluate(text => window.__onMessage({ type: 'aiState', enabled: true, mode: 'ai', text, eventId: 'opening', lineIndices: [0], displayRevision: 1 }), replacement);
  await page.locator('.terminal').getByText('开始之前，先确认今天的安排。', { exact: true }).waitFor();
  assert.doesNotMatch(await page.locator('.terminal').textContent(), /女战士先到了/);
  assert.equal(await page.locator('.terminal .term-btn').count(), 1);
  assert.equal(await page.locator('.terminal b').count(), 0);
  await page.evaluate(() => window.__onMessage({ type: 'aiState', enabled: true, mode: 'ai', text: 'STALE_REPLY', eventId: 'old', lineIndices: [0], displayRevision: 0 }));
  assert.doesNotMatch(await page.locator('.terminal').textContent(), /STALE_REPLY/);
  await page.evaluate(() => window.__onMessage({ type: 'aiState', enabled: true, mode: 'original', text: 'ORIGINAL_FALLBACK', eventId: 'opening', lineIndices: [0], displayRevision: 1 }));
  await page.locator('.terminal').getByText('ORIGINAL_FALLBACK', { exact: true }).waitFor();
  assert.doesNotMatch(await page.locator('.terminal').textContent(), /开始之前/);
  console.log('PASS: closed-panel main transcript displays recorded API opening; wrapping, menu geometry, regeneration, plain text, stale revision and fallback');
  const exitsBefore = await page.evaluate(() => window.eraTestMessages.filter(x => x.type === 'exitGame').length);
  await page.getByRole('button', { name: '更多操作', exact: true }).click();
  await page.getByText('返回游戏选择', { exact: true }).click();
  await page.getByRole('alertdialog', { name: '返回游戏选择？' }).waitFor();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.evaluate(() => window.eraTestMessages.filter(x => x.type === 'exitGame').length), exitsBefore);
  assert.match(await page.locator('.terminal').textContent(), /ORIGINAL_FALLBACK/);
  await page.getByRole('button', { name: '更多操作', exact: true }).click();
  await page.getByText('返回游戏选择', { exact: true }).click();
  await page.getByRole('button', { name: '返回选择', exact: true }).click();
  assert.equal(await page.evaluate(() => window.eraTestMessages.filter(x => x.type === 'exitGame').length), exitsBefore + 1);
  const scansBefore = await page.evaluate(() => window.eraTestMessages.filter(x => x.type === 'scanGames').length);
  await page.evaluate(() => window.__onMessage({ type: 'gameExited' }));
  await page.waitForFunction(n => window.eraTestMessages.filter(x => x.type === 'scanGames').length > n, scansBefore);
  await page.evaluate(() => window.__onMessage({ type: 'gamesScanned', games: [], rootDir: '/storage/emulated/0/ERA', rootDirExists: true }));
  await page.getByRole('button', { name: '选择游戏目录', exact: true }).waitFor();
  await page.screenshot({ path: path.join(screenshots, 'android-game-selection.png') });
  await page.getByRole('button', { name: 'AI 口上', exact: true }).click();
  await page.getByRole('button', { name: '当前口上', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '重新生成', exact: true }).isDisabled(), true);
  assert.doesNotMatch(await page.locator('.ai-dialogue').textContent(), /ORIGINAL_FALLBACK/);
  console.log('PASS: return-to-selection menu, cancellation without exit, confirmation, rescan and AI state reset');
  assert.deepEqual(errors, []);
  console.log('PASS: mobile layout, AI-first progress, diagnostics/export routing, regeneration, fallback and settings form');
} finally { await browser.close(); }
