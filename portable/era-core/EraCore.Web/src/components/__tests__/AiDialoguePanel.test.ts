// @vitest-environment happy-dom
import { describe, it, expect, vi } from 'vitest';
import { mount } from '@vue/test-utils';
import AiDialoguePanel from '../AiDialoguePanel.vue';
import { postInput } from '../../lib/mauiBridge';
vi.mock('../../lib/mauiBridge', () => ({ postInput: vi.fn() }));
describe('AI dialogue stays separate from game input', () => {
  it('edits generated function choices and notes without submitting a game action', async () => {
    vi.mocked(postInput).mockClear(); const wrapper = mount(AiDialoguePanel); await wrapper.get('.ai-launch').trigger('click');
    await wrapper.findAll('button').find(b => b.text() === '函数清单 / 编辑选择')!.trigger('click');
    expect(JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]).type).toBe('aiStoryDocument');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiStoryDocument', documentId: 'doc-a', state: 'ready', reason: '已建立', done: 1, total: 1, count: 1, page: 0, rows: [{ key: 'key-a', file: 'ERB/a.erb', function: 'KOJO_MISC', line: 3, classification: 'unknown', reason: '来源不确定', action: 'auto', note: '' }] } }));
    await wrapper.vm.$nextTick(); expect((wrapper.get('input[aria-label="优先 AI KOJO_MISC"]').element as HTMLInputElement).checked).toBe(false);
    await wrapper.get('input[aria-label="优先 AI KOJO_MISC"]').setValue(true);
    await wrapper.get('input[aria-label="备注 KOJO_MISC"]').setValue('可重复日常');
    await wrapper.findAll('button').find(b => b.text().startsWith('保存函数选择'))!.trigger('click');
    expect(JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0])).toEqual({ type: 'aiStoryDocumentSave', documentId: 'doc-a', edits: [{key: 'key-a', action: 'allow', note: '可重复日常'}] });
    expect(vi.mocked(postInput).mock.calls.some(c => JSON.parse(c[0]).type === 'input')).toBe(false);
    window.dispatchEvent(new CustomEvent('era-ai-reset')); await wrapper.vm.$nextTick(); await wrapper.get('.ai-launch').trigger('click');
    expect(wrapper.find('[aria-label="可编辑函数清单"]').exists()).toBe(false); wrapper.unmount();
  });
  it('shows the automatically selected template and clears it when leaving the game', async () => {
    const wrapper = mount(AiDialoguePanel); await wrapper.get('.ai-launch').trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiState', text: '原文', status: '保护', character: '旅人', busy: false, hasEvent: true, storyTemplateName: 'eraJourney0.92', storyTemplateReason: '名称关键词匹配；配置版本 0.92 一致' } }));
    await wrapper.vm.$nextTick(); expect(wrapper.get('[aria-label="内置剧情模板"]').text()).toContain('eraJourney0.92');
    expect(wrapper.get('[aria-label="内置剧情模板"]').text()).toContain('版本 0.92');
    window.dispatchEvent(new CustomEvent('era-ai-reset')); await wrapper.vm.$nextTick(); await wrapper.get('.ai-launch').trigger('click');
    expect(wrapper.get('[aria-label="内置剧情模板"]').text()).not.toContain('eraJourney0.92'); wrapper.unmount();
  });
  it('blocks regenerate for story and sends scoped overrides bound to the displayed event', async () => {
    vi.mocked(postInput).mockClear(); const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiState', text: '原剧情', status: '保护', character: '旅人', busy: false, hasEvent: true, canGenerate: false, storyReady: true, storyReason: '剧情父调用', storyLocation: 'event.erb:12', canSetFunctionRule: true, eventId: 'scene-1', storyTurn: 6 } }));
    await wrapper.vm.$nextTick();
    expect(wrapper.findAll('button').find(b => b.text() === '重新生成')!.attributes('disabled')).toBeDefined();
    expect(wrapper.get('[aria-label="剧情判断"]').text()).toContain('剧情父调用');
    await wrapper.findAll('button').find(b => b.text() === '仅本段允许')!.trigger('click');
    expect(JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0])).toEqual({ type: 'aiStoryRule', scope: 'event', action: 'allow', eventId: 'scene-1', storyTurn: 6 });
    await wrapper.findAll('button').find(b => b.text() === '本游戏此函数禁止')!.trigger('click');
    expect(JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]).scope).toBe('function');
    expect(vi.mocked(postInput).mock.calls.some(c => JSON.parse(c[0]).type === 'input')).toBe(false);
    window.dispatchEvent(new CustomEvent('era-ai-reset')); await wrapper.vm.$nextTick(); await wrapper.get('.ai-launch').trigger('click');
    expect(wrapper.findAll('button').find(b => b.text() === '仅本段允许')!.attributes('disabled')).toBeDefined(); wrapper.unmount();
  });
  it('saves automatic body/option translation independently from AI dialogue', async () => {
    vi.mocked(postInput).mockClear(); const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    await wrapper.findAll('button').find(b => b.text() === 'API 与酒馆预设')!.trigger('click');
    await wrapper.get('input[aria-label="自动翻译正文和选项"]').setValue(true);
    await wrapper.get('select[aria-label="翻译目标语言"]').setValue('zh-CN');
    await wrapper.get('input[aria-label="翻译输出 tokens"]').setValue('4096');
    await wrapper.findAll('button').find(b => b.text() === '保存设置')!.trigger('click');
    const saved = JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]);
    expect(saved.type).toBe('aiSave'); expect(saved.settings.Enabled).toBe(false);
    expect(saved.settings.TranslationEnabled).toBe(true); expect(saved.settings.TranslationLanguage).toBe('zh-CN'); expect(saved.settings.TranslationTokens).toBe(4096);
    vi.mocked(postInput).mockClear();
    await wrapper.get('input[aria-label="翻译输出 tokens"]').setValue('0');
    await wrapper.findAll('button').find(b => b.text() === '保存设置')!.trigger('click');
    expect(postInput).not.toHaveBeenCalled(); expect(wrapper.text()).toContain('翻译输出 tokens 必须是'); wrapper.unmount();
  });
  it('saves output budgets above 8192 exactly and blocks empty, fractional and nonpositive input', async () => {
    vi.mocked(postInput).mockClear(); const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    await wrapper.findAll('button').find(b => b.text() === 'API 与酒馆预设')!.trigger('click');
    const input = wrapper.get('input[aria-label="最大输出 tokens"]');
    const save = wrapper.findAll('button').find(b => b.text() === '保存设置')!;
    await input.setValue('32768'); await save.trigger('click');
    expect(JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]).settings.OutputTokens).toBe(32768);
    vi.mocked(postInput).mockClear();
    for (const value of ['', '0', '-1', '1.5', '2147483648']) {
      await input.setValue(value); await save.trigger('click');
      expect(wrapper.text()).toContain('必须是');
    }
    expect(postInput).not.toHaveBeenCalled(); wrapper.unmount();
  });
  it('returning to selection closes the panel and clears old dialogue and regeneration', async () => {
    const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiState', text: 'OLD_GAME_REPLY', status: 'AI', character: 'Old', busy: false, hasEvent: true } }));
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiPreview', text: 'OLD_GAME_PROMPT' } }));
    await wrapper.vm.$nextTick(); expect(wrapper.text()).toContain('OLD_GAME_REPLY');
    window.dispatchEvent(new CustomEvent('era-ai-reset'));
    await wrapper.vm.$nextTick(); expect(wrapper.find('[role="dialog"]').exists()).toBe(false);
    await wrapper.get('.ai-launch').trigger('click');
    expect(wrapper.text()).not.toContain('OLD_GAME_REPLY');
    expect(wrapper.find('textarea[aria-label="实际请求（不含密钥）"]').exists()).toBe(false);
    expect(wrapper.findAll('button').find(b => b.text() === '重新生成')!.attributes('disabled')).toBeDefined();
    wrapper.unmount();
  });
  it('shows a game style report and saves reasoning and token-source preferences', async () => {
    vi.mocked(postInput).mockClear(); const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    await wrapper.findAll('button').find(b => b.text() === '游戏风格')!.trigger('click');
    expect(JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]).type).toBe('aiStyle');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiStyle', text: '短句与第三人称叙述交替' } }));
    await wrapper.vm.$nextTick(); expect((wrapper.get('textarea[aria-label="当前游戏风格"]').element as HTMLTextAreaElement).value).toContain('第三人称');
    await wrapper.findAll('button').find(b => b.text() === 'API 与酒馆预设')!.trigger('click');
    await wrapper.get('select[aria-label="思考模式"]').setValue('disabled');
    await wrapper.get('input[aria-label="无原口上时补写"]').setValue(true);
    await wrapper.findAll('button').find(b => b.text() === '保存设置')!.trigger('click');
    const saved = JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]).settings;
    expect(saved.ThinkingMode).toBe('disabled'); expect(saved.UseGameStyle).toBe(true); expect(saved.UsePresetOutputTokens).toBe(false);
    expect(saved.GenerateWithoutOriginal).toBe(true);
    wrapper.unmount();
  });
  it('shows generation progress and routes logs/diagnostics separately from game actions', async () => {
    vi.mocked(postInput).mockClear(); const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiState', text: '', status: 'pending', character: 'Lin', busy: true, hasEvent: true } }));
    await wrapper.vm.$nextTick(); expect(wrapper.get('.ai-dialogue').text()).toContain('生成中');
    for (const name of ['生成日志', '导出日志', '测试已保存 API']) await wrapper.findAll('button').find(b => b.text() === name)!.trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiLog', text: 'HTTP 401 [REDACTED]' } }));
    await wrapper.vm.$nextTick(); expect((wrapper.get('textarea[aria-label="生成日志"]').element as HTMLTextAreaElement).value).toContain('401');
    expect(vi.mocked(postInput).mock.calls.map(c => JSON.parse(c[0]).type)).toEqual(['aiGet', 'aiLog', 'aiExportLog', 'aiProbe']);
    wrapper.unmount();
  });
  it('selects fetched models and saves entry toggles without game input', async () => {
    vi.mocked(postInput).mockClear();
    const wrapper = mount(AiDialoguePanel);
    await wrapper.get('.ai-launch').trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiPresetImported', text: JSON.stringify({ extra: 'x'.repeat(1100000), prompts: [{ identifier: 'a', name: 'Alpha', content: 'A' }, { identifier: 'b', name: 'Beta', content: 'B' }] }) } }));
    await wrapper.findAll('button').find(b => b.text() === 'API 与酒馆预设')!.trigger('click');
    expect(wrapper.findAll('.ai-entry')).toHaveLength(2);
    await wrapper.get('input[aria-label="启用 Alpha"]').setValue(false);
    await wrapper.findAll('.ai-entry button')[1]!.trigger('click');
    await wrapper.findAll('button').find(b => b.text() === '上移')!.trigger('click');
    await wrapper.findAll('button').find(b => b.text() === '刷新模型列表')!.trigger('click');
    const request = JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]);
    expect(request.type).toBe('aiModels'); expect(request.settings.PresetJson).toBeUndefined();
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiModels', requestId: request.requestId, models: ['test-model'], error: '' } }));
    await wrapper.vm.$nextTick();
    await wrapper.get('select[aria-label="可用模型"]').setValue('test-model');
    await wrapper.findAll('button').find(b => b.text() === '保存设置')!.trigger('click');
    const saved = JSON.parse(vi.mocked(postInput).mock.calls.at(-1)![0]);
    expect(saved.type).toBe('aiSave'); expect(saved.settings.Model).toBe('test-model');
    const preset = JSON.parse(saved.settings.PresetJson);
    expect(preset.extra.length).toBe(1100000);
    expect(preset.prompt_order[0].order).toEqual([{ identifier: 'b', enabled: true }, { identifier: 'a', enabled: false }]);
    expect(vi.mocked(postInput).mock.calls.map(c => JSON.parse(c[0]).type).every(t => t.startsWith('ai'))).toBe(true);
    wrapper.unmount();
  });
  it('regenerates and restores only through AI messages, and renders replies as text', async () => {
    vi.mocked(postInput).mockClear();
    const mouse = vi.fn(); window.addEventListener('mousedown', mouse);
    const wrapper = mount(AiDialoguePanel, { attachTo: document.body });
    await wrapper.get('.ai-launch').trigger('click');
    window.dispatchEvent(new CustomEvent('era-ai-message', { detail: { type: 'aiState', text: '<button onclick="bad()">hello</button>', status: 'AI', character: 'Lin', busy: false, hasEvent: true, canGenerate: true } }));
    await wrapper.vm.$nextTick();
    expect(wrapper.get('.ai-dialogue').text()).toContain('<button onclick=');
    expect(wrapper.find('.ai-dialogue button').exists()).toBe(false);
    const generate = wrapper.findAll('button').find(b => b.text() === '重新生成')!;
    await generate.trigger('mousedown');
    await generate.trigger('click'); await generate.trigger('click');
    await wrapper.findAll('button').find(b => b.text() === '恢复原口上 / 取消')!.trigger('click');
    const messages = vi.mocked(postInput).mock.calls.map(call => JSON.parse(call[0]));
    expect(messages.map(m => m.type)).toEqual(['aiGet', 'aiGenerate', 'aiGenerate', 'aiRestore']);
    expect(messages.every(m => !('value' in m))).toBe(true);
    expect(mouse).not.toHaveBeenCalled();
    window.removeEventListener('mousedown', mouse);
    wrapper.unmount();
  });
});
